// ---- 文件系统辅助 ---------------------------------------------------------
// 每个测试一个 /tmp 下的唯一子目录，RAII 清理。
struct TempDir {
    fs::path path;
    explicit TempDir(const char* tag) {
        static std::uint64_t counter = 0;
        const auto now = std::chrono::duration_cast<std::chrono::nanoseconds>(
                            std::chrono::system_clock::now().time_since_epoch())
                            .count();
        ++counter;
        std::error_code ec;
        const fs::path base = fs::temp_directory_path(ec);
        CHECK(!ec);
        CHECK(base.generic_string().rfind("/tmp", 0) == 0);
        path = base / ("mo2fmt_test_" + std::string(tag) + "_" + std::to_string(now) + "_" +
                       std::to_string(counter));
        fs::create_directories(path, ec);
        CHECK(!ec);
        CHECK(fs::is_directory(path));
    }
    ~TempDir() {
        std::error_code ec;
        fs::remove_all(path, ec);
    }
    TempDir(const TempDir&) = delete;
    TempDir& operator=(const TempDir&) = delete;
};

fs::path write_bytes(const fs::path& p, std::string_view content) {
    std::ofstream out(p, std::ios::binary | std::ios::trunc);
    CHECK(static_cast<bool>(out));
    out.write(content.data(), static_cast<std::streamsize>(content.size()));
    out.close();
    CHECK(!out.fail());
    return p;
}

std::string read_bytes(const fs::path& p) {
    std::ifstream in(p, std::ios::binary);
    CHECK(static_cast<bool>(in));
    return std::string(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
}

// 目录条目名，显式排序保证确定性。
std::vector<std::string> dir_entries(const fs::path& d) {
    std::vector<std::string> names;
    std::error_code ec;
    for (const auto& e : fs::directory_iterator(d, ec)) {
        names.push_back(e.path().filename().string());
    }
    CHECK(!ec);
    std::sort(names.begin(), names.end());
    return names;
}

template <class F>
bool throws_runtime(F&& f) {
    try {
        f();
    } catch (const std::runtime_error&) {
        return true;
    }
    return false;
}

// ---- 结构辅助 -------------------------------------------------------------
mol::ModEntry make_mod(std::string_view name, bool enabled, bool separator = false) {
    mol::ModEntry e;
    e.name.assign(name.begin(), name.end());
    e.enabled = enabled;
    e.separator = separator;
    return e;
}

mol::PluginEntry make_plugin(std::string_view name, bool enabled) {
    mol::PluginEntry e;
    e.name.assign(name.begin(), name.end());
    e.enabled = enabled;
    return e;
}

std::string to_std(const mol::string& s) { return std::string(s.begin(), s.end()); }

// wine_to_unix 的便捷包装：走默认 memory_resource，转成 std::string 便于比对。
std::string wu(std::string_view p, std::string_view pfx) {
    return to_std(mol::wine_to_unix(p, pfx));
}

// ###name[enabled]/... 便于一行比对全部字段。
std::string dump_mods(const mol::vector<mol::ModEntry>& v) {
    std::string s;
    for (const auto& e : v) {
        s += '|';
        s += e.enabled ? '+' : '-';
        s += std::string(e.name.begin(), e.name.end());
        if (e.separator) {
            s += "%SEP";
        }
    }
    return s;
}

std::string dump_plugins(const mol::vector<mol::PluginEntry>& v) {
    std::string s;
    for (const auto& e : v) {
        s += '|';
        s += e.enabled ? '+' : '-';
        s += std::string(e.name.begin(), e.name.end());
    }
    return s;
}

std::string join(const mol::vector<mol::string>& v) {
    std::string s;
    for (const auto& e : v) {
        s += '|';
        s += std::string(e.begin(), e.end());
    }
    return s;
}

std::string opt_str(const std::optional<mol::string>& v) {
    if (!v) {
        return "<nullopt>";
    }
    return std::string(v->begin(), v->end());
}

