TEST(modlist_read_separator_flag) {
    TempDir dir("modlist");
    const fs::path p = write_bytes(dir.path / "modlist.txt",
        "-Body_Sep__separator\n"
        "+Head_separator\n"
        "-separator\n"     // 不以 _separator 结尾
        "+Exactly_separato\n");
    const auto v = mol::read_modlist(p.string());
    CHECK_EQ(dump_mods(v),
             std::string("|+Exactly_separato|-separator|+Head_separator%SEP|-Body_Sep__separator%SEP"));
    CHECK_EQ(v.size(), 4u);
    CHECK(!v[0].separator);  // Exactly_separato
    CHECK(!v[1].separator);  // separator
    CHECK(v[2].separator);    // Head_separator
    CHECK(v[3].separator);    // Body_Sep__separator
}

TEST(modlist_write_roundtrip_atomic) {
    TempDir dir("modlist");
    const fs::path p = dir.path / "modlist.txt";

    mol::vector<mol::ModEntry> low_to_high;
    low_to_high.push_back(make_mod("Alpha", true));
    low_to_high.push_back(make_mod("Beta", false));
    low_to_high.push_back(make_mod("Head_separator", true, true));
    mol::write_modlist(p.string(), low_to_high);

    // 原子写：目录里只有目标文件，无临时文件残留。
    const auto entries = dir_entries(dir.path);
    CHECK_EQ(entries.size(), 1u);
    if (!entries.empty()) {
        CHECK_EQ(entries[0], std::string("modlist.txt"));
    }

    const std::string expected =
        "# This file was automatically generated by Mod Organizer.\n"
        "+Head_separator\n"   // 最高优先级写最前
        "-Beta\n"
        "+Alpha\n";
    CHECK_EQ(read_bytes(p), expected);

    const auto back = mol::read_modlist(p.string());
    CHECK_EQ(dump_mods(back), std::string("|+Alpha|-Beta|+Head_separator%SEP"));
    CHECK_EQ(back.size(), 3u);
}

TEST(modlist_write_overwrites_existing) {
    TempDir dir("modlist");
    const fs::path p = dir.path / "modlist.txt";
    write_bytes(p, "stale content that must be replaced\n");

    mol::vector<mol::ModEntry> low_to_high;
    low_to_high.push_back(make_mod("Only", true));
    mol::write_modlist(p.string(), low_to_high);

    const auto entries = dir_entries(dir.path);
    CHECK_EQ(entries.size(), 1u);
    CHECK_EQ(read_bytes(p), std::string("# This file was automatically generated by Mod Organizer.\n+Only\n"));
    const auto back = mol::read_modlist(p.string());
    CHECK_EQ(dump_mods(back), std::string("|+Only"));
}

