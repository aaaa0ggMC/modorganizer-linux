TEST(wine_to_unix_cases) {
    const std::string pfx = "/prefix";
    CHECK_EQ(wu("Z:\\home\\u\\x", pfx), std::string("/home/u/x"));
    CHECK_EQ(wu("z:\\home", pfx), std::string("/home"));
    CHECK_EQ(wu("C:\\Users\\u", pfx), std::string("/prefix/drive_c/Users/u"));
    CHECK_EQ(wu("c:\\users\\u", pfx), std::string("/prefix/drive_c/users/u"));
    CHECK_EQ(wu("C:", pfx), std::string("/prefix/drive_c"));
    CHECK_EQ(wu("C:\\", pfx), std::string("/prefix/drive_c"));
    CHECK_EQ(wu("D:\\Games", pfx), std::string("/prefix/dosdevices/d:/Games"));
    CHECK_EQ(wu("d:", pfx), std::string("/prefix/dosdevices/d:"));
    CHECK_EQ(wu("C:\\a\\..\\b", pfx), std::string("/prefix/drive_c/a/../b"));  // 不折叠 ..
    CHECK_EQ(wu("/already/a/unix/path", pfx), std::string("/already/a/unix/path"));
    // 双反斜杠视作分隔符
    CHECK_EQ(wu("C:\\\\Users\\\\u", pfx), std::string("/prefix/drive_c/Users/u"));
    CHECK_EQ(wu("Z:\\\\home", pfx), std::string("/home"));
    // 单个正斜杠分隔符
    CHECK_EQ(wu("C:/Users/u", pfx), std::string("/prefix/drive_c/Users/u"));
}

