TEST(modlist_read_reverses_and_skips_unmanaged) {
    TempDir dir("modlist");
    const fs::path p = write_bytes(dir.path / "modlist.txt",
        "# This file was automatically generated by Mod Organizer.\n"
        "+Alpha\n"                 // 最高优先级（文件第一条）
        "\n"
        "-Beta\n"
        "*ForeignMod\n"            // 未管理：跳过
        "# a comment\n"
        "+Gamma\n");               // 最低优先级

    const auto v = mol::read_modlist(p.string());
    // 文件顺序反转后（低→高）：Gamma, Beta, Alpha
    CHECK_EQ(dump_mods(v), std::string("|+Gamma|-Beta|+Alpha"));
    CHECK_EQ(v.size(), 3u);
    CHECK(v[0].enabled);    // Gamma
    CHECK(!v[1].enabled);  // Beta
    CHECK(v[2].enabled);    // Alpha
}

TEST(modlist_read_crlf_and_bom) {
    TempDir dir("modlist");
    const fs::path p = write_bytes(dir.path / "modlist.txt",
        "\xEF\xBB\xBF# header\r\n"
        "+Alpha\r\n"
        "-Beta\r\n"
        "# comment\r\n"
        "\r\n"
        "*Foreign\r\n");
    const auto v = mol::read_modlist(p.string());
    CHECK_EQ(dump_mods(v), std::string("|-Beta|+Alpha"));
    CHECK_EQ(v.size(), 2u);
    CHECK(!v[0].enabled);
    CHECK(v[1].enabled);
}

